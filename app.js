function currentScenarios() { return SCENARIOS[state.track]; }

function renderScenario(index) {
  state.stage2.index = index;
  const list = currentScenarios();
  const s = list[index];
  const trackLabel = TRACKS.find((t) => t.key === state.track).name;
  $("stage2Title").textContent = `ภารกิจภาคสนาม — สาย ${trackLabel}`;
  $("stage2Fill").style.width = `${(index / list.length) * 100}%`;
  $("stage2Progress").textContent = `สถานการณ์ ${index + 1} / ${list.length}${index === list.length - 1 ? " · เสรีภาพสื่อมวลชน" : ""}`;

  $("scenarioCode").textContent = s.code;
  $("scenarioTitle").textContent = s.title;
  $("scenarioArticles").textContent = "มาตราที่เกี่ยวข้อง: " + s.articles;
  $("scenarioText").textContent = s.text;
  $("meterDot").style.opacity = "0";
  $("scenarioReasonBlock").hidden = true;
  $("scenarioReason").value = "";
  $("scenarioReveal").hidden = true;
  $("btnScenarioConfirm").hidden = false;
  $("btnScenarioConfirm").disabled = true;
  $("btnScenarioNext").hidden = true;

  let chosen = null;
  const wrap = $("scenarioChoices");
  wrap.innerHTML = "";
  s.options.forEach((opt, i) => {
    const b = document.createElement("button");
    b.className = "choice-btn";
    b.textContent = opt.text;
    b.addEventListener("click", () => {
      chosen = i;
      [...wrap.children].forEach((el) => el.classList.remove("selected"));
      b.classList.add("selected");
      $("meterDot").style.opacity = "1";
      $("meterDot").style.left = opt.meter + "%";
      $("scenarioReasonBlock").hidden = false;
      $("btnScenarioConfirm").disabled = false;
    });
    wrap.appendChild(b);
  });

  $("btnScenarioConfirm").onclick = () => {
    if (chosen === null) return;
    const opt = s.options[chosen];
    [...wrap.children].forEach((el) => el.disabled = true);
    state.rightsPoints += opt.best ? 15 : 5;
    const reasonText = $("scenarioReason").value.trim();
    state.insightPoints += insightFromText(reasonText, 15);
    state.stage2.answers[index] = { chosen, best: opt.best, reason: reasonText };
    updateHud();

    $("scenarioLegal").textContent = s.legal;
    $("scenarioRealWorld").textContent = s.realworld;
    $("scenarioHook").textContent = s.hook;
    $("scenarioReveal").hidden = false;
    $("btnScenarioConfirm").hidden = true;
    $("btnScenarioNext").hidden = false;

    if (index === list.length - 1 && opt.best && !state.badges.includes("media")) state.badges.push("media");
    saveState();
  };
  saveState();
}

$("btnScenarioNext").addEventListener("click", () => {
  const list = currentScenarios();
  const next = state.stage2.index + 1;
  if (next < list.length) { renderScenario(next); }
  else {
    $("stage2Fill").style.width = "100%";
    showScreen("stage3");
    renderBoss();
  }
});

