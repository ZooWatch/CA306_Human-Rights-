function insightFromText(text, minLen) {
  if (!text) return 0;
  const trimmed = text.trim();
  if (trimmed.length < (minLen || 10)) return trimmed.length > 0 ? 2 : 0;
  const keywords = ["สิทธิ", "มาตรา", "กฎหมาย", "ความเป็นส่วนตัว", "เสรีภาพ", "จริยธรรม", "ผู้บริโภค", "ประโยชน์สาธารณะ", "ยินยอม", "ศักดิ์ศรี"];
  const hits = keywords.filter((k) => trimmed.includes(k)).length;
  let pts = 5;
  if (trimmed.length >= 60) pts += 3;
  if (hits >= 1) pts += 3;
  if (hits >= 3) pts += 4;
  return pts;
}

